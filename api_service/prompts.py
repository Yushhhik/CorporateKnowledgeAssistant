import re
from typing import List, Dict

# Единственный источник правды для отказа: его же использует main.py, когда поиск ничего не нашёл.
NO_ANSWER = "Я не нашел точного ответа в документации. Переключить на оператора?"
# Модели просим отказываться коротким служебным словом, а не готовой фразой: фразу из промпта небольшие модели
# выдают слишком охотно, даже когда во фрагментах есть ответ. Слово код заменяет на NO_ANSWER (llm_service.clean_answer).
REFUSE_TOKEN = "НЕТ_ОТВЕТА"

SYSTEM_PROMPT = """Ты — ассистент первой линии поддержки БАРС Груп. Отвечай на вопрос сотрудника, используя ТОЛЬКО фрагменты документации ниже.
Правила:
1. Отвечай строго на заданный вопрос и больше ни на что. Не предлагай и не придумывай другие вопросы и темы.
2. Если во фрагментах есть ответ или его часть — ответь по ним: перескажи шаги, названия кнопок, условия и цифры так, как они написаны. Если ответ неполный, дай то, что есть, и коротко скажи, чего не хватает.
3. Отказ — крайняя мера. Если фрагменты вообще не про тему вопроса, ответь одним словом "__NO_ANSWER__" и ничего больше. Если фрагменты хоть как-то по теме, отказываться нельзя: перескажи самое близкое из них (разделы, экраны, кнопки, функции, роли, условия) и коротко скажи, чего не хватает.
4. Ничего не выдумывай: названия кнопок, шаги, числа и ссылки бери только из фрагментов. Знания о других системах не используй.
5. Не пиши строку "Источник" и номера страниц: источники добавляются автоматически.
6. Отвечай по-русски, на "Вы", кратко и по делу; шаги оформляй нумерованным списком.
7. Опечатки и разговорные формулировки вопроса не мешают: опирайся на смысл.
Фрагменты документации:
__CONTEXT__"""

# Оговорка про «реестр техники» добавляется кодом (main.py), а не промптом:
# примеры и частные правила в промпте маленькая модель переносит в ответы на посторонние вопросы.
FURNITURE_NOTE = "В документации описан только реестр мебели, реестра техники нет."
_TECH_REGISTRY = re.compile(r"реестр\w*\s+(?:\w+\s+)?техник", re.IGNORECASE)


def furniture_note(question: str, context: str) -> str | None:
    """Оговорка, если спрашивают про реестр техники, а в найденном тексте только мебель."""
    if _TECH_REGISTRY.search(question or "") and "мебел" in (context or "").lower():
        return FURNITURE_NOTE
    return None


# Для небольшой модели важен размер запроса: длинная история вытесняет правила и контекст
HISTORY_MESSAGES = 6          # три последних обмена
HISTORY_ITEM_CHARS = 300
_SOURCE_LINE = re.compile(r"(?im)^\s*источник(?:и)?\s*[:—-].*$")


def _is_refusal(text: str) -> bool:
    return text.startswith(NO_ANSWER[:30])


def _clean_history(history: List[str]) -> List[Dict]:
    """История в хронологическом порядке без отказов, источников и длинных хвостов.

    Отказы из истории убираем: увидев в диалоге «не нашел ответа», модель начинает
    отвечать так же на нормальные вопросы.
    """
    items: List[Dict] = []

    for msg in reversed(history):
        if msg.startswith("Пользователь:"):
            role, content = "user", msg[len("Пользователь:"):].strip()
        elif msg.startswith("Бот:"):
            role, content = "assistant", msg[len("Бот:"):].strip()
        else:
            role, content = "user", msg.strip()

        if role == "assistant":
            content = _SOURCE_LINE.sub("", content).strip()

            if _is_refusal(content):
                if items and items[-1]["role"] == "user":
                    items.pop()          # вместе с вопросом, на который отказали
                continue

        if content:
            items.append({"role": role, "content": content[:HISTORY_ITEM_CHARS]})

    return items[-HISTORY_MESSAGES:]


VISION_CONTEXT_CHARS = 1500   # маленькому окну vision-модели нужно место под саму картинку

VISION_PROMPT = """Ты — ассистент первой линии поддержки БАРС Груп. Сотрудник прислал изображение: скриншот, схему или фото из рабочей системы. Отвечай по-русски, на "Вы", кратко.
Правила:
1. Опиши только то, что реально видно на изображении: какая система и экран, кнопки, поля и надписи (переписывай дословно), сообщения об ошибках. Если есть вопрос сотрудника, ответь на него по изображению.
2. Ничего не угадывай и не дополняй. Если надпись или деталь нечитаема, так и скажи и попроси прислать более чёткое изображение.
3. Фрагменты документации ниже используй, только если они явно относятся к тому, что на изображении. Иначе игнорируй их.
4. Не пиши строку "Источник" и номера страниц.
__DOCS__"""


def build_prompt(context: str, history: List[str], question: str, has_image: bool = False) -> List[Dict]:
    if has_image:
        # С картинкой отказ «контекст пустой» неуместен: модель должна посмотреть на изображение
        docs = (
            f"Фрагменты документации:\n{context.strip()[:VISION_CONTEXT_CHARS]}"
            if context and context.strip()
            else "Фрагментов документации по этому изображению нет."
        )
        system_content = VISION_PROMPT.replace("__DOCS__", docs)
    elif not context or context.strip() == "":
        system_content = (
            "Ты — корпоративный ассистент БАРС Груп. "
            "Контекст пустой, поэтому на любой вопрос отвечай дословно: "
            f"'{NO_ANSWER}'"
        )
    else:
        # replace, а не str.format: фигурные скобки в тексте документации не должны ломать промпт
        system_content = (
            SYSTEM_PROMPT
            .replace("__NO_ANSWER__", REFUSE_TOKEN)
            .replace("__CONTEXT__", context)
        )

    system_message = {
        "role": "system",
        "content": system_content
    }

    # История вопросов путает vision-модель и съедает её контекстное окно
    history_messages = [] if has_image else _clean_history(history)

    user_message = {"role": "user", "content": question}
    return [system_message] + history_messages + [user_message]
