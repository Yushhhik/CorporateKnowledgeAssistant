from typing import List, Dict
SYSTEM_PROMPT = """Ты — корпоративный ассистент службы поддержки БАРС Груп.
Отвечай ТОЛЬКО на основе предоставленного контекста из документации.
Правила:
1. Если в контексте есть ответ — дай четкий структурированный ответ
   (с заголовками, нумерацией шагов, если это инструкция).
2. Обязательно в конце указывай источник в формате:
   "Источник: {{название файла}}, стр. {{номер страницы}}".
3. Если в контексте НЕТ ответа на вопрос, напиши дословно:
   "Я не нашел точного ответа в документации. Переключить на оператора?"
   и НЕ придумывай ничего от себя.
4. Обращайся к пользователю на "Вы", тон дружелюбный, профессиональный.
5. Можно использовать эмодзи, но без фанатизма.
6. Если вопрос про интерфейс БО (как выглядит кнопка, где найти элемент) —
   опиши словами расположение, так как картинки ты не видишь.
7. Если в вопросе встречается ссылка вида bo.bars.group — объясни,
   что это ссылка на документ БАРС-Офис с примененным фильтром.
8. Если вопрос про синтаксис фильтров (например, "!> 200") — объясни
   правила из документации, не додумывай.
9. Если пользователь спрашивает про 'реестр техники', а в контексте описана
'мебель', отвечай: 'В документации описан только реестр мебели, реестра техники
нет. Возможно, вы имели в виду реестр мебели?'
Вот контекст из документации:
{context}
"""


def build_prompt(context: str, history: List[str], question: str) -> List[Dict]:
    if not context or context.strip() == "":
        system_content = (
            "Ты — корпоративный ассистент БАРС Груп. "
            "Контекст пустой, поэтому на любой вопрос отвечай: "
            "'Я не нашел точного ответа в документации. Переключить на оператора?'"
        )
    else:
        system_content = SYSTEM_PROMPT.format(context=context)

    system_message = {
        "role": "system",
        "content": system_content
    }

    history_messages = []
    for msg in reversed(history):
        if "Пользователь:" in msg:
            role = "user"
            content = msg.replace("Пользователь:", "").strip()
        elif "Бот:" in msg or "Бот —" in msg:
            role = "assistant"
            content = msg.replace("Бот:", "").replace("Бот —", "").strip()
        else:
            role = "user"
            content = msg
        history_messages.append({"role": role, "content": content})

    user_message = {"role": "user", "content": question}
    return [system_message] + history_messages + [user_message]
