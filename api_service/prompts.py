from typing import List, Dict

# Единственный источник правды для отказа: его же использует main.py, когда поиск ничего не нашёл.
NO_ANSWER = "Я не нашел точного ответа в документации. Переключить на оператора?"

SYSTEM_PROMPT = """Ты — корпоративный ассистент службы поддержки БАРС Груп.
Критически важные правила:
1. Отвечай только по контексту ниже. Если в контексте нет ответа на вопрос — напиши дословно и ничего больше: "__NO_ANSWER__"
2. Строго запрещено выдумывать факты, шаги, названия кнопок, цифры и ссылки, которых нет в контексте. Не используй свои знания о других системах.
3. Не пиши строку "Источник" и не называй номера страниц: источники добавляются автоматически.
Дополнительные правила:
4. Обращайся на "Вы", тон дружелюбный и профессиональный.
5. Если вопрос про "реестр техники", а в контексте только "мебель" — сначала скажи: "В документации описан только реестр мебели, реестра техники нет. Возможно, вы имели в виду реестр мебели?" и только потом дай ответ по мебели из контекста.
6. Если вопрос про интерфейс — опиши расположение элементов словами, опираясь на контекст.
7. Если контекст относится к другой теме, чем вопрос, считай, что ответа нет (правило 1).
Примеры правильных ответов:
Вопрос: Где найти производственный календарь?
Контекст: Производственный календарь находится в нижней части главного меню БАРС-Офис.
Ответ: Производственный календарь находится в нижней части главного меню БАРС-Офис.
Вопрос: Как приготовить борщ?
Контекст: (пусто или не по теме)
Ответ: __NO_ANSWER__
Вот контекст из документации:
__CONTEXT__"""


def build_prompt(context: str, history: List[str], question: str) -> List[Dict]:
    if not context or not context.strip():
        system_content = (
            "Ты — корпоративный ассистент БАРС Груп. "
            "Контекст пустой, поэтому на любой вопрос отвечай дословно: "
            f"'{NO_ANSWER}'"
        )
    else:
        # replace, а не str.format: фигурные скобки в тексте документации не должны ломать промпт
        system_content = (
            SYSTEM_PROMPT
            .replace("__NO_ANSWER__", NO_ANSWER)
            .replace("__CONTEXT__", context)
        )

    system_message = {
        "role": "system",
        "content": system_content
    }

    # В Redis история лежит от новых сообщений к старым, для модели нужен хронологический порядок
    history_messages = []
    for msg in reversed(history):
        if msg.startswith("Пользователь:"):
            role = "user"
            content = msg[len("Пользователь:"):].strip()
        elif msg.startswith("Бот:"):
            role = "assistant"
            content = msg[len("Бот:"):].strip()
        else:
            role = "user"
            content = msg
        history_messages.append({"role": role, "content": content})

    user_message = {"role": "user", "content": question}
    return [system_message] + history_messages + [user_message]
